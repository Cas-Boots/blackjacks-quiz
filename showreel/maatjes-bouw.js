// Copies the maatjes (the quiz's pixel animals) into the film: node maatjes-bouw.js
// It reads app/src/lib/shared/pixeldieren.ts, so the film shows exactly the animals
// the players pick, with the same smoothing, light and shadow. It writes maatjes.js.
// Run it again after an animal is redrawn in the app. Needs Node 22.18 or newer,
// which reads TypeScript; on an older Node, add --experimental-strip-types.
const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const BRON = path.join(__dirname, '..', 'app', 'src', 'lib', 'shared', 'pixeldieren.ts');
const B32 = '0123456789abcdefghijklmnopqrstuv';

// one layer: per colour, its pixels as two characters each (x, y in base 32)
function pak(laag) {
  return laag.map(({ kleur, d }) => {
    let p = '';
    for (const m of d.matchAll(/M(\d+) (\d+)h1v1h-1z/g)) p += B32[+m[1]] + B32[+m[2]];
    return [kleur, p];
  });
}

import(pathToFileURL(BRON).href).then(m => {
  const uit = {};
  for (const sleutel of Object.keys(m.SPRITES)) {
    const l = m.lagenVan(sleutel);
    const dier = { oog: l.oog };
    for (const [naam, laag] of Object.entries(l)) if (Array.isArray(laag) && laag.length) dier[naam] = pak(laag);
    uit[sleutel] = dier;
  }
  const js = `// Generated by \`node maatjes-bouw.js\` from app/src/lib/shared/pixeldieren.ts. Do not edit.\n` +
    `// Each layer is a list of [colour, pixels]; a pixel is two base-32 characters (x, y) on a 32×32 grid.\n` +
    `(function (root) {\n  const MAATJES = ${JSON.stringify(uit)};\n` +
    `  if (typeof module !== 'undefined' && module.exports) module.exports = MAATJES; else root.MAATJES = MAATJES;\n})(this);\n`;
  fs.writeFileSync(path.join(__dirname, 'maatjes.js'), js);
  console.log(`maatjes.js: ${Object.keys(uit).length} maatjes, ${(js.length / 1024).toFixed(0)} kB`);
});
